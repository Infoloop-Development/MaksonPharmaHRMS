/** Opens print dialog directly via a hidden iframe (no extra browser tab). */
export function openReportPrintWindow(options: ReportPrintOptions): boolean {
  const html = buildReportPrintHtml(options);
  const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);

  try {
    const iframe = document.createElement('iframe');
    iframe.setAttribute('title', 'Report print');
    iframe.style.cssText =
      'position:fixed;width:0;height:0;border:0;opacity:0;pointer-events:none;left:-9999px';
    document.body.appendChild(iframe);

    const cleanup = () => {
      iframe.remove();
      URL.revokeObjectURL(url);
    };

    iframe.onload = () => {
      const win = iframe.contentWindow;
      if (!win) {
        cleanup();
        return;
      }
      const onAfterPrint = () => {
        win.removeEventListener('afterprint', onAfterPrint);
        cleanup();
      };
      win.addEventListener('afterprint', onAfterPrint);
      setTimeout(() => {
        win.focus();
        win.print();
        setTimeout(cleanup, 120_000);
      }, 300);
    };

    iframe.src = url;
    return true;
  } catch {
    URL.revokeObjectURL(url);
    return false;
  }
}
