import type { CompanyBranding } from './companyBranding';

export type ReportPrintColumn = {
  key: string;
  label: string;
  mono?: boolean;
};

export type ReportPrintOptions = {
  branding: CompanyBranding;
  title: string;
  subtitle?: string;
  summaryLine?: string;
  columns: ReportPrintColumn[];
  rows: Record<string, string | number>[];
  signatoryOnLastPage?: boolean;
};

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function escapeCssString(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ');
}

function formatGeneratedAt(): string {
  return new Date().toLocaleDateString('en-IN', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  });
}

function renderTableRows(
  columns: ReportPrintColumn[],
  rows: Record<string, string | number>[]
): string {
  return rows
    .map((row) => {
      const cells = columns
        .map((col) => {
          const raw = row[col.key];
          const value = raw === undefined || raw === null || raw === '' ? '—' : String(raw);
          const cls = [
            col.mono ? 'mono' : '',
            col.key === 'status' && value === 'Present' ? 'status-present' : '',
            col.key === 'status' && value === 'Absent' ? 'status-absent' : '',
          ]
            .filter(Boolean)
            .join(' ');
          return `<td${cls ? ` class="${cls}"` : ''}>${escapeHtml(value)}</td>`;
        })
        .join('');
      return `<tr>${cells}</tr>`;
    })
    .join('');
}

function renderSignatory(branding: CompanyBranding): string {
  if (!branding.signatoryName.trim()) return '';
  const designation = branding.signatoryDesignation.trim() || 'Authorized Signatory';
  return `
    <div class="signatory-block">
      <div class="signatory-line">${escapeHtml(branding.signatoryName)}</div>
      <div class="signatory-desig">${escapeHtml(designation)}</div>
    </div>
    <div class="generated-by">Generated by MAMS</div>
  `;
}

